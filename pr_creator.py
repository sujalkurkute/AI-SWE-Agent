"""
Day 4: PR Creation
Once a fix is verified (tests pass in the sandbox), this module:
1. Creates a new branch
2. Commits the fix
3. Pushes it
4. Opens a Pull Request on GitHub with a clear description
"""
import os
from datetime import datetime
from git import Repo
from github import Github, Auth
from dotenv import load_dotenv

load_dotenv()


def create_branch_and_commit(repo_path: str, diff_text: str, branch_name: str, commit_message: str) -> bool:
    """Create a new branch, apply the diff to the REAL repo copy, and commit."""
    repo = Repo(repo_path)
    repo.git.checkout("-b", branch_name)

    # GitPython's repo.git.* commands already run with the working directory
    # set to repo_path - so writing to os.path.join(repo_path, ...) but then
    # passing that SAME joined path to a git command causes git to look for
    # it relative to repo_path AGAIN, effectively doubling the path and
    # failing with "No such file or directory". The fix: write using the
    # full path (correct for Python's own file I/O, which uses the
    # process's cwd), but pass only the bare filename to git commands
    # (correct for git, which already treats repo_path as its cwd).
    diff_filename = "_agent_fix.diff"
    diff_file = os.path.join(repo_path, diff_filename)
    # newline='' avoids Windows re-translating any \r\n already in diff_text
    with open(diff_file, "w", newline="") as f:
        f.write(diff_text)

    try:
        repo.git.apply(diff_filename)
    finally:
        os.remove(diff_file)

    repo.git.add(A=True)
    repo.git.commit("-m", commit_message)
    return True


def push_branch(repo_path: str, branch_name: str, remote_name: str = "origin"):
    repo = Repo(repo_path)
    repo.git.push(remote_name, branch_name)


def build_pr_body(bug_explanation: str, test_output: str, static_analysis_summary: str = "") -> str:
    """Build a clear, honest PR description - always disclosing AI authorship."""
    return f"""## Summary
This fix was generated by an automated AI SWE Agent and has been verified
against the existing test suite in an isolated sandbox.

## Root Cause
{bug_explanation}

## Test Results
```
{test_output[-1500:] if len(test_output) > 1500 else test_output}
```

{f"## Static Analysis{chr(10)}{static_analysis_summary}" if static_analysis_summary else ""}

---
**Note:** This PR was created by an AI agent. Please review carefully before merging.
Generated: {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}
"""


def open_pull_request(
    repo_owner: str,
    repo_name: str,
    branch_name: str,
    base_branch: str,
    title: str,
    body: str,
) -> str:
    """Open a PR via the GitHub API. Returns the PR URL."""
    token = os.getenv("GITHUB_TOKEN")
    if not token:
        raise RuntimeError(
            "GITHUB_TOKEN not found. Add it to your .env file:\n  GITHUB_TOKEN=ghp_your_token_here"
        )

    gh = Github(auth=Auth.Token(token))
    gh_repo = gh.get_repo(f"{repo_owner}/{repo_name}")

    pr = gh_repo.create_pull(
        title=title,
        body=body,
        head=branch_name,
        base=base_branch,
    )
    return pr.html_url


def full_pr_pipeline(
    repo_path: str,
    repo_owner: str,
    repo_name: str,
    diff_text: str,
    bug_explanation: str,
    test_output: str,
    base_branch: str = "main",
) -> str:
    """End-to-end: branch -> commit -> push -> open PR. Returns the PR URL."""
    branch_name = f"agent-fix-{datetime.utcnow().strftime('%Y%m%d%H%M%S')}"
    commit_message = f"Fix: {bug_explanation[:72]}"

    create_branch_and_commit(repo_path, diff_text, branch_name, commit_message)
    push_branch(repo_path, branch_name)

    pr_body = build_pr_body(bug_explanation, test_output)
    pr_url = open_pull_request(
        repo_owner, repo_name, branch_name, base_branch,
        title=f"[AI Agent] Fix: {bug_explanation[:60]}",
        body=pr_body,
    )
    return pr_url


